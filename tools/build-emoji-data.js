#!/usr/bin/env node
/*
 * Regenerate ui/emoji-data.js, the designer's emoji search list. Run by hand when you
 * want newer emoji. Nothing runs this at startup.
 *
 *   curl -so data.json https://cdn.jsdelivr.net/npm/emojibase-data@16.0.3/en/data.json
 *   node tools/build-emoji-data.js data.json
 *
 * Source: emojibase-data (https://emojibase.dev, MIT license, by Miles Johnson).
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const SOURCE = 'emojibase-data@16.0.3 en/data.json';
const input = process.argv[2];
if (!input) {
  console.error('Usage: node tools/build-emoji-data.js path/to/emojibase-data/en/data.json');
  process.exit(1);
}

// Group 2 is "component" (skin tones, hair styles); entries without a group are
// regional indicator letters. Neither is useful as a piece icon. Skin-tone variants
// live under `skins` and are left out.
const entries = JSON.parse(fs.readFileSync(input, 'utf8'))
  .filter((e) => e.group !== undefined && e.group !== 2)
  .sort((a, b) => a.order - b.order)
  .map((e) => [e.emoji, e.label, (e.tags || []).join(' ')]);

